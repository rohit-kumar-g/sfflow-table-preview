'use strict';
// "Ask with AI": saves the flow summary as Markdown and hands it to an AI agent
// already present in VS Code. No API keys: each target uses its own sign-in.

const vscode = require('vscode');
const path = require('path');

const LAST_TARGET_KEY = 'sfflowPreview.lastAiTarget';
const CLAUDE_CODE_ID = 'anthropic.claude-code';
const AGENTFORCE_ID = 'salesforce.salesforcedx-einstein-gpt';

// Rough size guard for inline prompts (characters, not tokens)
const MAX_INLINE_CHARS = 120000;

function config() {
    return vscode.workspace.getConfiguration('sfflowPreview');
}

async function ensureDir(uri) {
    try {
        await vscode.workspace.fs.createDirectory(uri);
    } catch (e) {
        // already exists
    }
}

async function exists(uri) {
    try {
        await vscode.workspace.fs.stat(uri);
        return true;
    } catch (e) {
        return false;
    }
}

// Writes <folder>/<ApiName>.flow-summary.md and returns its Uri.
async function writeSummaryFile(context, sourceUri, apiName, markdown) {
    const folderSetting = String(config().get('summaryFolder') ?? '').trim();
    const wsFolder = sourceUri ? vscode.workspace.getWorkspaceFolder(sourceUri) : undefined;
    let folder;
    if (wsFolder && folderSetting) {
        folder = vscode.Uri.joinPath(wsFolder.uri, ...folderSetting.split(/[\\/]+/).filter(Boolean));
        await ensureDir(folder);
        // keep generated summaries out of git
        const gitignore = vscode.Uri.joinPath(folder, '.gitignore');
        if (!(await exists(gitignore))) {
            await vscode.workspace.fs.writeFile(gitignore, Buffer.from('# generated by Salesforce Flow Table Preview\n*\n', 'utf8'));
        }
    } else {
        folder = vscode.Uri.joinPath(context.globalStorageUri, 'summaries');
        await ensureDir(folder);
    }
    const safeName = (apiName || 'Flow').replace(/[^A-Za-z0-9_.-]/g, '_');
    const fileUri = vscode.Uri.joinPath(folder, `${safeName}.flow-summary.md`);
    await vscode.workspace.fs.writeFile(fileUri, Buffer.from(markdown, 'utf8'));
    return fileUri;
}

// Path as an agent in this workspace should see it: relative when inside a workspace folder.
function displayPath(uri) {
    const ws = vscode.workspace.getWorkspaceFolder(uri);
    if (ws) return path.relative(ws.uri.fsPath, uri.fsPath).split(path.sep).join('/');
    return uri.fsPath;
}

async function availableTargets() {
    const targets = [];
    const commands = new Set(await vscode.commands.getCommands(true));

    if (vscode.extensions.getExtension(CLAUDE_CODE_ID) && commands.has('claude-vscode.editor.open')) {
        targets.push({ id: 'claudeCode', label: '$(sparkle) Claude Code', detail: 'Opens a new Claude Code tab with the prompt; Claude reads the saved summary file.' });
    }
    if (vscode.extensions.getExtension(AGENTFORCE_ID) && commands.has('agentforce.injectPromptToInput')) {
        targets.push({ id: 'agentforce', label: '$(hubot) Agentforce', detail: 'Puts the prompt and summary in the Agentforce chat input.' });
    }
    if (commands.has('workbench.action.chat.open')) {
        targets.push({ id: 'chat', label: '$(comment-discussion) VS Code Chat', detail: 'Opens the Chat view (Copilot or another chat participant) with the prompt and summary.' });
    }
    try {
        const models = await vscode.lm.selectChatModels();
        for (const m of models) {
            targets.push({
                id: 'languageModel', model: m,
                label: `$(symbol-misc) Answer here with ${m.name}`,
                detail: `Language model from ${m.vendor}; the answer appears in the preview.`
            });
        }
    } catch (e) {
        // language model API not available
    }
    targets.push({ id: 'clipboard', label: '$(copy) Copy prompt to clipboard', detail: 'Paste it into any agent or chat.' });
    targets.push({ id: 'openFile', label: '$(markdown) Open summary file', detail: 'Opens the saved Markdown so an agent that reads open files can use it.' });
    return targets;
}

async function pickTarget(context, targets) {
    const configured = config().get('aiTarget') || 'ask';
    if (configured !== 'ask') {
        const match = targets.find(t => t.id === configured);
        if (match) return match;
        vscode.window.showWarningMessage(`SF Flow: AI target "${configured}" is not available here; choose another.`);
    }
    const last = context.globalState.get(LAST_TARGET_KEY);
    const items = targets.map(t => ({ ...t, description: t.id === last ? 'last used' : undefined }));
    items.sort((a, b) => (b.id === last) - (a.id === last));
    const picked = await vscode.window.showQuickPick(items, {
        title: 'Ask with AI: where should the flow summary go?',
        matchOnDetail: true
    });
    if (picked) await context.globalState.update(LAST_TARGET_KEY, picked.id);
    return picked;
}

function limitInline(text) {
    if (text.length <= MAX_INLINE_CHARS) return text;
    return text.substring(0, MAX_INLINE_CHARS) + '\n\n(SUMMARY TRUNCATED: it is longer than the inline limit; the full summary is in the saved file.)';
}

/**
 * @param {object} args
 * @param {vscode.ExtensionContext} args.context
 * @param {vscode.Uri} args.sourceUri       the flow XML
 * @param {string} args.apiName
 * @param {string} args.summaryMarkdown     renderAiSummary() output
 * @param {string} [args.question]          typed in the preview; empty = default prompt
 * @param {(msg: object) => void} args.post send a message to the preview webview
 */
async function askWithAi({ context, sourceUri, apiName, summaryMarkdown, question, post }) {
    const prompt = (question && question.trim()) || String(config().get('defaultPrompt') || '').trim();
    const summaryUri = await writeSummaryFile(context, sourceUri, apiName, summaryMarkdown);
    const summaryPath = displayPath(summaryUri);
    const sourcePath = sourceUri ? displayPath(sourceUri) : '';
    const inlinePrompt = `${prompt}\n\nFLOW:\n\n${limitInline(summaryMarkdown)}`;

    const target = await pickTarget(context, await availableTargets());
    if (!target) return;

    switch (target.id) {
        case 'claudeCode': {
            // @-mention files inside the workspace; outside it, give the absolute path
            const ref = p => (path.isAbsolute(p) ? p : `@${p}`);
            const claudePrompt = `${prompt}\n\nThe flow is summarized in ${ref(summaryPath)}`
                + (sourcePath ? ` (generated from the metadata ${ref(sourcePath)})` : '')
                + '. Read the summary first and the XML only if you need more detail.';
            try {
                // claude-vscode.editor.open(sessionId?, initialPrompt?) opens a new tab with the prompt
                await vscode.commands.executeCommand('claude-vscode.editor.open', undefined, claudePrompt);
            } catch (e) {
                await vscode.env.clipboard.writeText(claudePrompt);
                await vscode.commands.executeCommand('claude-vscode.editor.open');
                vscode.window.showInformationMessage('SF Flow: the prompt is on the clipboard; paste it into Claude Code.');
            }
            break;
        }
        case 'agentforce':
            await vscode.commands.executeCommand('agentforce.injectPromptToInput', { prompt: inlinePrompt });
            break;
        case 'chat':
            await vscode.commands.executeCommand('workbench.action.chat.open', { query: inlinePrompt, isPartialQuery: true });
            break;
        case 'languageModel':
            await answerWithModel(target.model, inlinePrompt, post);
            break;
        case 'clipboard':
            await vscode.env.clipboard.writeText(inlinePrompt);
            vscode.window.showInformationMessage(`SF Flow: prompt and summary copied (${inlinePrompt.length.toLocaleString()} characters).`);
            break;
        case 'openFile':
        default: {
            const doc = await vscode.workspace.openTextDocument(summaryUri);
            await vscode.window.showTextDocument(doc, { viewColumn: vscode.ViewColumn.Beside, preview: false });
            break;
        }
    }
}

async function answerWithModel(model, promptText, post) {
    const cts = new vscode.CancellationTokenSource();
    post({ type: 'aiStart', model: `${model.name} (${model.vendor})` });
    try {
        const messages = [vscode.LanguageModelChatMessage.User(
            'You are an expert at troubleshooting and explaining Salesforce flows.\n\n' + promptText)];
        const response = await model.sendRequest(messages, {
            justification: 'Explain the Salesforce flow shown in the Flow Table Preview.'
        }, cts.token);
        for await (const fragment of response.text) {
            post({ type: 'aiChunk', text: fragment });
        }
        post({ type: 'aiDone' });
    } catch (e) {
        post({ type: 'aiError', text: e && e.message ? e.message : String(e) });
    } finally {
        cts.dispose();
    }
}

module.exports = { askWithAi, writeSummaryFile };
